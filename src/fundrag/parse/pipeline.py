"""Parse every stored KID into a JSON file (for the code) and a Markdown file (for you).

Output, one pair per document version, named by doc_id from the manifest:
    data/processed/kid/<doc_id>.json   sections with pages and text, plus a parse report
    data/processed/kid/<doc_id>.md     the same content, readable in VS Code's preview

Parsing is deterministic and cheap, so files are only rewritten when the parser
version changes or you pass --force. The parser version is stored in every file:
if the parsing rules improve, old outputs can be found and regenerated.
"""

from __future__ import annotations

import json
from dataclasses import dataclass
from datetime import UTC, date, datetime
from pathlib import Path

from pydantic import BaseModel

from fundrag import config
from fundrag.collect import manifest
from fundrag.parse.kid import Section, check_sections, extract_pages, split_sections

PARSER_VERSION = "kid-sections-1"


class ParsedDocument(BaseModel):
    doc_id: str
    isin: str
    issuer: str
    doc_type: str
    language: str
    doc_date: date | None
    source: str
    raw_path: str
    parser_version: str
    parsed_at: datetime
    n_pages: int
    n_chars: int
    sections: list[Section]
    problems: list[str]

    def section(self, key: str) -> Section | None:
        return next((s for s in self.sections if s.key == key), None)


def parse_record(record: manifest.ManifestRecord, data_dir: Path | None = None) -> ParsedDocument:
    data_dir = data_dir or config.DATA_DIR
    pages = extract_pages(data_dir / record.path)
    sections = split_sections(pages)
    problems = check_sections(sections)
    n_chars = sum(len(p) for p in pages)
    if n_chars < 2000:
        problems.append(f"very little text ({n_chars} characters); scanned or broken PDF?")
    return ParsedDocument(
        doc_id=record.doc_id,
        isin=record.isin,
        issuer=record.issuer,
        doc_type=record.doc_type,
        language=record.language,
        doc_date=record.doc_date,
        source=record.source,
        raw_path=record.path,
        parser_version=PARSER_VERSION,
        parsed_at=datetime.now(UTC),
        n_pages=len(pages),
        n_chars=n_chars,
        sections=sections,
        problems=problems,
    )


def to_markdown(doc: ParsedDocument) -> str:
    lines = [
        f"<!-- generated by fundrag parse ({doc.parser_version}); do not edit -->",
        f"# KID {doc.isin} ({doc.doc_date or 'undated'})",
        "",
        f"- doc_id: `{doc.doc_id}`  ",
        f"- source: {doc.source}  ",
        f"- problems: {', '.join(doc.problems) if doc.problems else 'none'}",
        "",
    ]
    for s in doc.sections:
        pages = f"p. {s.page_start}" if s.page_start == s.page_end else (
            f"pp. {s.page_start}-{s.page_end}"
        )
        hashes = "#" * (s.level + 1) if s.level else "##"
        lines += [f"{hashes} {s.title or s.key} _({s.key}, {pages})_", ""]
        if s.text:
            # Two trailing spaces force a line break in Markdown, so table rows stay rows.
            lines += [ln + "  " for ln in s.text.splitlines()]
            lines.append("")
    return "\n".join(lines)


def output_paths(doc_id: str, out_dir: Path | None = None) -> tuple[Path, Path]:
    out_dir = out_dir or config.PROCESSED_DIR / "kid"
    return out_dir / f"{doc_id}.json", out_dir / f"{doc_id}.md"


def load(doc_id: str, out_dir: Path | None = None) -> ParsedDocument:
    json_path, _ = output_paths(doc_id, out_dir)
    return ParsedDocument.model_validate_json(json_path.read_text(encoding="utf-8"))


@dataclass
class ParseOutcome:
    isin: str
    doc_id: str
    status: str  # parsed | unchanged | failed
    problems: list[str]
    n_sections: int = 0


def parse_all(
    force: bool = False,
    data_dir: Path | None = None,
    manifest_path: Path | None = None,
    out_dir: Path | None = None,
) -> list[ParseOutcome]:
    """Parse the latest KID of every ISIN in the manifest."""
    latest = manifest.latest_by_isin(manifest.load(manifest_path))
    outcomes = []
    for isin, record in sorted(latest.items()):
        json_path, md_path = output_paths(record.doc_id, out_dir)
        if not force and json_path.exists():
            existing = json.loads(json_path.read_text(encoding="utf-8"))
            if existing.get("parser_version") == PARSER_VERSION:
                outcomes.append(ParseOutcome(isin, record.doc_id, "unchanged",
                                             existing.get("problems", [])))  # fmt: skip
                continue
        try:
            doc = parse_record(record, data_dir)
        except Exception as exc:  # noqa: BLE001 - one bad PDF must not stop the batch
            outcomes.append(ParseOutcome(isin, record.doc_id, "failed", [str(exc)]))
            continue
        json_path.parent.mkdir(parents=True, exist_ok=True)
        json_path.write_text(doc.model_dump_json(indent=2), encoding="utf-8")
        md_path.write_text(to_markdown(doc), encoding="utf-8")
        outcomes.append(ParseOutcome(isin, record.doc_id, "parsed", doc.problems,
                                     len(doc.sections)))  # fmt: skip
    return outcomes
